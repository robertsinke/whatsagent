/**
 * Refresh the vendored provider model catalog at
 * `shared/provider-catalog.generated.ts` from `https://models.dev/api.json`.
 *
 * Run manually on a cadence (e.g. monthly, or when a new Claude/GPT family
 * ships). Never runs at request time — the file is 3.2 MB upstream and a
 * settings page load is not allowed to fetch it.
 *
 *   tsx scripts/refresh-provider-catalog.ts            # regenerate the file
 *   tsx scripts/refresh-provider-catalog.ts --check     # offline integrity check
 *
 * `--check` is OFFLINE ONLY and is what `npm run check` wires in. It must pass
 * on a plane, exactly like `scripts/patch-baileys.mjs --check` and
 * `scripts/check-migrations.mjs`. It never fetches; it verifies the generated
 * file on disk is structurally sound (banner present, manual aliases present,
 * both providers non-empty, no duplicate ids within a provider).
 *
 * Ollama is deliberately ABSENT from the catalog — it is enumerated live from
 * `GET /api/tags` at request time. See
 * docs/plans/2026-07-27-001-oss-readiness-plan.md "Model enumeration reality".
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const outPath = join(repoRoot, 'shared', 'provider-catalog.generated.ts');

const BANNER =
	'// GENERATED by scripts/refresh-provider-catalog.ts — DO NOT EDIT BY HAND.\n' +
	'// Regenerate with `npm run refresh:provider-catalog`. Hand-maintained aliases\n' +
	'// (MANUAL_ALIASES below) are prepended by the generator and survive every run.\n' +
	'// Source: https://models.dev/api.json (build-time only; never fetched at runtime).\n';

/**
 * Hand-maintained aliases models.dev does not list, but `claude --model` accepts.
 * `claude --help` documents only `--model <alias|full-id>`. These are prepended
 * to the claude catalog on every regeneration and survive across runs.
 */
const MANUAL_ALIASES: Record<'claude' | 'codex', Array<{ id: string; name: string }>> = {
	claude: [
		{ id: 'opus', name: 'Opus (alias)' },
		{ id: 'sonnet', name: 'Sonnet (alias)' },
		{ id: 'haiku', name: 'Haiku (alias)' }
	],
	codex: []
};

const CLAUDE_CAP = 12;
const CODEX_CAP = 12;
const MODELS_DEV_URL = 'https://models.dev/api.json';

interface ModelsDevModel {
	id: string;
	name?: string;
	release_date?: string;
}

interface ModelsDevProvider {
	id: string;
	models: Record<string, ModelsDevModel>;
}

type ModelsDevApi = Record<string, ModelsDevProvider>;

/** Codex CLI plausibly accepts ids matching `gpt-5`, `codex`, or `o<digits>`. */
const CODEX_ID_PATTERN = /^(gpt-5|codex|o\d)/;

function sortByReleaseDesc(a: ModelsDevModel, b: ModelsDevModel): number {
	return (b.release_date ?? '').localeCompare(a.release_date ?? '');
}

function pickClaude(api: ModelsDevApi): ModelsDevModel[] {
	const anthropic = api.anthropic;
	if (!anthropic?.models) throw new Error('models.dev: anthropic provider missing models');
	return Object.values(anthropic.models).sort(sortByReleaseDesc).slice(0, CLAUDE_CAP);
}

function pickCodex(api: ModelsDevApi): ModelsDevModel[] {
	const openai = api.openai;
	if (!openai?.models) throw new Error('models.dev: openai provider missing models');
	return Object.values(openai.models)
		.filter((m) => CODEX_ID_PATTERN.test(m.id))
		.sort(sortByReleaseDesc)
		.slice(0, CODEX_CAP);
}

function escape(s: string): string {
	return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function emitEntry(provider: 'claude' | 'codex', m: { id: string; name?: string; release_date?: string }): string {
	const name = m.name || m.id;
	const parts = [
		`id: '${escape(m.id)}'`,
		`name: '${escape(name)}'`
	];
	if (m.release_date) parts.push(`releaseDate: '${escape(m.release_date)}'`);
	return `\t\t{ ${parts.join(', ')} }`;
}

function emitProviderBlock(provider: 'claude' | 'codex', models: ModelsDevModel[]): string {
	const aliasLines = MANUAL_ALIASES[provider].map((a) =>
		emitEntry(provider, { id: a.id, name: a.name })
	);
	const modelLines = models.map((m) => emitEntry(provider, m));
	const all = [...aliasLines, ...modelLines];
	return `\t${provider}: [\n${all.join(',\n')}\n\t]`;
}

function buildFile(claude: ModelsDevModel[], codex: ModelsDevModel[]): string {
	return (
		BANNER +
		'\n' +
		'import type { CatalogModel, DraftProviderName } from \'./provider-types.js\';\n' +
		'\n' +
		'/**\n' +
		' * Vendored model catalog for the provider dropdown. Only `claude` and\n' +
		' * `codex` are catalogued here; `ollama` is enumerated live from /api/tags.\n' +
		' * See docs/plans/2026-07-27-001-oss-readiness-plan.md.\n' +
		' */\n' +
		'export const PROVIDER_CATALOG: Readonly<Record<Exclude<DraftProviderName, \'ollama\'>, readonly CatalogModel[]>> = {\n' +
		emitProviderBlock('claude', claude) +
		',\n' +
		emitProviderBlock('codex', codex) +
		'\n};\n'
	);
}

async function fetchApi(): Promise<ModelsDevApi> {
	const res = await fetch(MODELS_DEV_URL, { redirect: 'follow' });
	if (!res.ok) throw new Error(`models.dev/api.json returned HTTP ${res.status}`);
	return (await res.json()) as ModelsDevApi;
}

async function regenerate(): Promise<void> {
	const api = await fetchApi();
	const claude = pickClaude(api);
	const codex = pickCodex(api);
	const body = buildFile(claude, codex);
	await writeFile(outPath, body, 'utf8');
	console.log(`refreshed ${outPath} (claude ${claude.length} + aliases, codex ${codex.length})`);
}

interface CheckProblem {
	file: string;
	message: string;
}

async function readGenerated(): Promise<string> {
	try {
		return await readFile(outPath, 'utf8');
	} catch (cause) {
		throw new Error(`provider-catalog.generated.ts missing — run \`npm run refresh:provider-catalog\``, {
			cause
		});
	}
}

async function check(): Promise<void> {
	const source = await readGenerated();
	const problems: CheckProblem[] = [];

	if (!source.startsWith('// GENERATED by scripts/refresh-provider-catalog.ts')) {
		problems.push({ file: outPath, message: 'do-not-edit banner missing or altered' });
	}
	if (!source.includes("from './provider-types.js'")) {
		problems.push({ file: outPath, message: 'missing CatalogModel type import' });
	}
	if (!source.includes('export const PROVIDER_CATALOG')) {
		problems.push({ file: outPath, message: 'PROVIDER_CATALOG export missing' });
	}
	// Manual aliases must survive every regeneration.
	for (const alias of MANUAL_ALIASES.claude) {
		if (!source.includes(`id: '${alias.id}'`)) {
			problems.push({ file: outPath, message: `manual alias '${alias.id}' missing from claude block` });
		}
	}
	// Both providers must be present and non-empty (aliases alone satisfy claude;
	// codex has no aliases so its block must contain at least one entry).
	const claudeMatch = source.match(/claude:\s*\[([\s\S]*?)\n\t\]/);
	const codexMatch = source.match(/codex:\s*\[([\s\S]*?)\n\t\]/);
	if (!claudeMatch) problems.push({ file: outPath, message: 'claude block missing' });
	if (!codexMatch) problems.push({ file: outPath, message: 'codex block missing' });
	if (claudeMatch && !claudeMatch[1].includes('id:')) {
		problems.push({ file: outPath, message: 'claude block has no model entries' });
	}
	if (codexMatch && !codexMatch[1].includes('id:')) {
		problems.push({ file: outPath, message: 'codex block has no model entries' });
	}
	// No duplicate ids within a provider.
	for (const provider of ['claude', 'codex'] as const) {
		const block = provider === 'claude' ? claudeMatch?.[1] : codexMatch?.[1];
		if (!block) continue;
		const ids = [...block.matchAll(/id: '([^']+)'/g)].map((m) => m[1]);
		const dupes = ids.filter((id, i) => ids.indexOf(id) !== i);
		if (dupes.length > 0) {
			problems.push({ file: outPath, message: `${provider} has duplicate ids: ${[...new Set(dupes)].join(', ')}` });
		}
	}

	if (problems.length > 0) {
		console.error('provider-catalog check failed:\n');
		for (const p of problems) console.error('  * ' + p.message);
		console.error('');
		console.error('  Run `npm run refresh:provider-catalog` to regenerate.');
		process.exit(1);
	}
	console.log('provider-catalog ok: banner, aliases, and both providers present');
}

async function main(): Promise<void> {
	if (process.argv.includes('--check')) {
		await check();
	} else {
		await regenerate();
	}
}

await main();