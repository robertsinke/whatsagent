#!/usr/bin/env node
/**
 * Generate `server/store/migrations.generated.ts` — a module that embeds every
 * `server/store/migrations/*.sql` as a string. `db.ts` imports from this module
 * instead of reading SQL from disk at runtime, so the compiled server finds
 * its migrations wherever it lives: the repo, a `build/` directory, an Electron
 * asar, or any other packaged layout. (asar makes read-from-disk meaningfully
 * harder; embedding sidesteps it entirely.)
 *
 * The `.sql` files remain the source of truth — `check-migrations.mjs` still
 * validates numbering on them. This script is a build step, not a replacement:
 * it runs in `check` (to keep the generated module in sync) and in `build:server`
 * (so the compiled output carries the SQL).
 *
 * Idempotent: if the on-disk module already matches what would be generated, the
 * file is not touched, so `check` stays a no-op on a clean tree.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'server', 'store', 'migrations');
const outFile = join(root, 'server', 'store', 'migrations.generated.ts');

const files = readdirSync(migrationsDir)
	.filter((name) => /^\d+.*\.sql$/.test(name))
	.sort();

if (files.length === 0) {
	console.error('generate-migrations: no .sql files found in', migrationsDir);
	process.exit(1);
}

const entries = files.map((file) => {
	const version = Number.parseInt(file, 10);
	if (!Number.isFinite(version)) {
		console.error(`generate-migrations: bad version in ${file}`);
		process.exit(1);
	}
	const sql = readFileSync(join(migrationsDir, file), 'utf8');
	return { version, name: file, sql };
});

function serialize(sql) {
	// Escape backticks and `${` so template literals stay literal.
	return '`' + sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
}

const body =
	'// AUTO-GENERATED by scripts/generate-migrations.mjs — do not edit by hand.\n' +
	'// Source of truth: server/store/migrations/*.sql\n' +
	'export interface MigrationSql {\n' +
	'\tversion: number;\n' +
	'\tname: string;\n' +
	'\tsql: string;\n' +
	'}\n' +
	'export const MIGRATIONS: readonly MigrationSql[] = Object.freeze([\n' +
	entries
		.map(
			(e) =>
				`\t{ version: ${e.version}, name: ${JSON.stringify(e.name)}, sql: ${serialize(e.sql)} }`
		)
		.join(',\n') +
	'\n]);\n';

const check = process.argv.includes('--check');

if (check) {
	if (!existsSync(outFile)) {
		console.error('generate-migrations: generated module missing — run `node scripts/generate-migrations.mjs`');
		process.exit(1);
	}
	if (readFileSync(outFile, 'utf8') !== body) {
		console.error('generate-migrations: generated module is stale — run `node scripts/generate-migrations.mjs`');
		process.exit(1);
	}
	console.log(`generate-migrations: up to date (${files.length} migrations)`);
} else if (existsSync(outFile) && readFileSync(outFile, 'utf8') === body) {
	console.log(`generate-migrations: up to date (${files.length} migrations)`);
} else {
	writeFileSync(outFile, body, 'utf8');
	console.log(`generate-migrations: wrote ${outFile} (${files.length} migrations)`);
}